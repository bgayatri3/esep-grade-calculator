func TestGradeTypeString(t *testing.T) {
	tests := []struct {
		gt       GradeType
		expected string
	}{
		{Assignment, "assignment"},
		{Exam, "exam"},
		{Essay, "essay"},
	}

	for _, tt := range tests {
		if tt.gt.String() != tt.expected {
			t.Errorf("expected %s, got %s", tt.expected, tt.gt.String())
		}
	}
}
